async function policyPdf(): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle("Vendor Master Policy");
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const W = 595, H = 842, M = 56, maxW = W - 2 * M;
  let page = doc.addPage([W, H]);
  let y = H - M;
  const wrap = (text: string, f: typeof font, size: number) => {
    const words = text.split(" ");
    const lines: string[] = [];
    let cur = "";
    for (const w of words) {
      const next = cur ? `${cur} ${w}` : w;
      if (f.widthOfTextAtSize(next, size) > maxW) (lines.push(cur), (cur = w));
      else cur = next;
    }
    if (cur) lines.push(cur);
    return lines;
  };
  const write = (text: string, f = font, size = 10.5, gap = 4) => {
    for (const line of wrap(text, f, size)) {
      if (y < M + 30) ((page = doc.addPage([W, H])), (y = H - M));
      page.drawText(line, { x: M, y, size, font: f, color: rgb(0.1, 0.1, 0.1) });
      y -= size + gap;
    }
  };
  write(COMPANY.name, bold, 16);
  write("Vendor Master Policy · Finance & Accounts · Version 3.2 · Effective 1 April 2026", font, 10);
  y -= 10;
  for (const s of POLICY_SECTIONS) {
    y -= 6;
    write(s.title, bold, 12.5, 6);
    for (const r of s.rules) (write(r), (y -= 4));
  }
  y -= 10;
  write("Approved by: Anil Shetty, Finance Head. Owner: Accounts Payable.", font, 9);
  write("SPECIMEN: fictional document generated for the Theseus Mini simulation.", font, 8);
  return doc.save({ useObjectStreams: false });
}

/* ------------------------------------------------------ Word templates */

const p = (text: string, opts: { bold?: boolean; heading?: (typeof HeadingLevel)[keyof typeof HeadingLevel]; size?: number } = {}) =>
  new Paragraph({ ...(opts.heading ? { heading: opts.heading } : {}), spacing: { after: 120 }, children: [new TextRun({ text, bold: opts.bold, size: opts.size })] });

const kvTable = (rows: Array<[string, string]>) =>
  new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: rows.map(([k, v]) => new TableRow({ children: [new TableCell({ width: { size: 35, type: WidthType.PERCENTAGE }, children: [p(k, { bold: true })] }), new TableCell({ children: [p(v)] })] })),
  });

/** Fields: docxtemplater tags in {curly} braces. Each tag sits in ONE text run so it always renders. */
