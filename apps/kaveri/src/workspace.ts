/**
 * The employee's local workspace: real files on disk next to the websites.
 *   Vendor Desk/Vendor Register.xlsx     team tracker (open cases for T-2026-14 + history)
 *   Vendor Desk/Policies/Vendor Master Policy.pdf   the SOP the agent must read and follow
 *   Vendor Desk/Templates/*.docx         templates the agent fills (docxtemplater {tags})
 *   Vendor Desk/Bidders/                 where downloaded bidder documents go
 *   Payments/W41/                        batch export, bank upload CSV, report
 *   Outbox/                              generated letters / drafts
 * Regenerated on every world reset. A marker file guards deletion: we only
 * ever wipe a folder that this generator created.
 */
export const MARKER = ".kaveri-workspace";
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
export const DEFAULT_WORKSPACE = process.env.KAVERI_WORKSPACE ?? join(REPO_ROOT, "workspace");

export const WORKSPACE_FILES = {
  register: "Vendor Desk/Vendor Register.xlsx",
  policy: "Vendor Desk/Policies/Vendor Master Policy.pdf",
  empanelmentTemplate: "Vendor Desk/Templates/Empanelment Note.docx",
  reportTemplate: "Vendor Desk/Templates/Payment Integrity Report.docx",
  biddersDir: "Vendor Desk/Bidders",
  batchDir: "Payments/W41",
  outbox: "Outbox",
} as const;

/** Top-level entries a generated workspace (and the agents working in it) can contain. */
const OWN_ENTRIES = new Set([MARKER, "Vendor Desk", "Payments", "Outbox", "Drafts", "Attachments", "desktop.ini", ".DS_Store"]);

export async function generateWorkspace(state: KaveriState, dir = DEFAULT_WORKSPACE): Promise<string> {
  if (existsSync(dir)) {
    const entries = await readdir(dir);
    // Ours if it has the marker, or (a reset that was interrupted) only folders we create ourselves.
    const ours = entries.includes(MARKER) || entries.every((e) => OWN_ENTRIES.has(e));
    if (!ours) throw new Error(`Refusing to reset ${dir}: it isn't a Kaveri workspace (no ${MARKER} marker). Move it away or set KAVERI_WORKSPACE.`);
    // Empty it but keep the folder itself (the app may be watching it), the user's attachments and the
    // marker (so a reset that fails half-way still recognises the folder next time).
    const stuck: string[] = [];
    for (const e of entries) {
      if (e === "Attachments" || e === MARKER) continue;
      // Windows: a folder being watched, or a file open in Excel/Word, can refuse deletion for a moment.
      await rm(join(dir, e), { recursive: true, force: true, maxRetries: 8, retryDelay: 150 }).catch(() => stuck.push(e));
    }
    if (stuck.length)
      throw new Error(`Couldn't clear ${stuck.join(", ")} in the workspace. Is a file from it open in Excel, Word or a PDF viewer? Close it and press ↻ again.`);
  }
  for (const d of [WORKSPACE_FILES.biddersDir, WORKSPACE_FILES.batchDir, WORKSPACE_FILES.outbox, "Vendor Desk/Policies", "Vendor Desk/Templates"])
    await mkdir(join(dir, d), { recursive: true });
  await writeFile(join(dir, MARKER), `Generated by Kaveri for scenario date ${state.today}. Safe to delete; regenerated on world reset.\n`);
  await writeFile(join(dir, WORKSPACE_FILES.register), await vendorRegister(state));
  await writeFile(join(dir, WORKSPACE_FILES.policy), await policyPdf());
  await writeFile(join(dir, WORKSPACE_FILES.empanelmentTemplate), await empanelmentTemplate());
  await writeFile(join(dir, WORKSPACE_FILES.reportTemplate), await reportTemplate());
  return dir;
}

/* ------------------------------------------------------- Vendor Register */

export const REGISTER_COLUMNS = [
  "Case ID", "Tender", "Bidder", "Received on", "Docs complete", "GSTIN check", "PAN match", "Bank (penny-drop)",
  "MSME (Udyam)", "Duplicates / conflicts", "Debarment", "ERP vendor id", "Status", "Notes",
] as const;

async function vendorRegister(state: KaveriState): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "Kaveri Infra · Vendor Desk";
  const cases = wb.addWorksheet("Onboarding cases", { views: [{ state: "frozen", ySplit: 1 }] });
  cases.columns = REGISTER_COLUMNS.map((h) => ({ header: h, key: h, width: h === "Notes" ? 48 : h === "Bidder" ? 34 : 16 }));
  // History: closed cases from earlier tenders (filler vendors that are now active).
  const awarded = state.tenders.filter((t) => t.status === "awarded");
  let n = 101;
  for (const t of awarded)
    for (const name of t.qualifiedBidders) {
      const v = state.vendors.find((x) => x.legalName === name);
      cases.addRow({
        "Case ID": `VC-2026-${n++}`, Tender: t.id, Bidder: name, "Received on": "2026-05-1" + (n % 9), "Docs complete": "Yes",
        "GSTIN check": v?.gstin ? "Active" : "Not registered (declaration)", "PAN match": "Yes", "Bank (penny-drop)": "Name matches",
        "MSME (Udyam)": v?.udyam?.category ?? "none", "Duplicates / conflicts": "None", Debarment: "Clear", "ERP vendor id": v?.id ?? "",
        Status: "Closed: Active", Notes: "",
      });
    }
  // Open cases for this week's work.
  const received: Record<string, string> = { A: "2026-10-02", B: "2026-10-02", C: "2026-10-03" };
  for (const [k, b] of Object.entries(BIDDERS))
    cases.addRow({ "Case ID": `VC-2026-${n++}`, Tender: "T-2026-14", Bidder: b.legalName, "Received on": received[k], Status: "Docs received", Notes: "" });
  cases.getRow(1).font = { bold: true };
  cases.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE8EEF5" } };
  cases.autoFilter = { from: "A1", to: "N1" };

  const log = wb.addWorksheet("Bank change log", { views: [{ state: "frozen", ySplit: 1 }] });
  log.columns = ["Date", "Vendor ID", "Vendor", "Old account", "New account", "Requested via", "Call-back ref", "Verified by"].map((h) => ({ header: h, key: h, width: 20 }));
  for (const v of state.vendors)
    for (const h of v.history.filter((x) => x.field === "bank")) {
      const before = h.before as { accountNumber: string; ifsc: string };
      const after = h.after as { accountNumber: string; ifsc: string };
      const cb = /call-back (CB-\d+)/.exec(h.source ?? "")?.[1] ?? "";
      log.addRow({
        Date: h.at.slice(0, 10), "Vendor ID": v.id, Vendor: v.legalName, "Old account": `${before.accountNumber} / ${before.ifsc}`,
        "New account": `${after.accountNumber} / ${after.ifsc}`, "Requested via": h.source?.startsWith("email") ? h.source : "Letter",
        "Call-back ref": cb, "Verified by": cb ? h.by.replace("user:", "") : "",
      });
    }
  log.getRow(1).font = { bold: true };

  const help = wb.addWorksheet("How to use");
  help.getColumn(1).width = 110;
  [
    "Vendor Desk register: one row per onboarding case. Update the check columns as you verify each document.",
    "Status values: Docs received → Under verification → Pending approval → Closed: Active | Parked (reason in Notes) | Escalated (reason in Notes).",
    "Every bank change must have a call-back reference (phone call to the number already on record). See the Vendor Master Policy.",
  ].forEach((t) => help.addRow([t]));
  return Buffer.from(await wb.xlsx.writeBuffer());
}

